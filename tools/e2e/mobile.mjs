import assert from 'node:assert/strict';
import { launch } from '../lib/browser.mjs';
import { client, startServer } from '../lib/server.mjs';
import { demoAccount } from '../lib/demo.mjs';
const srv = await startServer(), api = await demoAccount(client(srv.url), { lang: 'en' });
const browser = await launch();
const context = await browser.newContext({ permissions: ['notifications'], reducedMotion: 'reduce' });
await context.addCookies([{ name: 'sc_session', value: api.cookie.split('=')[1], url: srv.url }]);
const page = await context.newPage();
let passed = 0;
const check = (name) => { passed++; console.log(`PASS ${name}`); };
const until = async (fn) => { for (let i = 0; i < 80; i++) { if (await fn()) return; await new Promise((r) => setTimeout(r, 100)); } throw new Error('Timed out'); };
try {
  await api.put('inbox', { items: [], lists: [] });
  await page.goto(`${srv.url}/tasks?add=1`);
  await page.locator('#tk-new').waitFor();
  await page.evaluate(() => navigator.serviceWorker.ready);
  await until(() => page.evaluate(() => !!navigator.serviceWorker.controller));
  // a second visit under the worker's control fills its data cache; only then is the app opened offline
  await page.reload(); await page.locator('#tk-new').waitFor();
  assert.equal(await page.locator('#tk-new').evaluate((e) => e === document.activeElement), true);
  check('Add task shortcut focuses input');
  await context.setOffline(true);
  await page.locator('#tk-new').fill('Persist through offline reload');
  await page.locator('#tk-new').press('Enter');
  await until(() => page.locator('.offline-queue').textContent().then((s) => s.includes('1 changes')));
  await page.reload();
  await page.getByText('Persist through offline reload', { exact: true }).waitFor();
  check('offline queue survives reload');
  await context.setOffline(false);
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await until(async () => (await api.get('inbox')).value.items.some((x) => x.text === 'Persist through offline reload'));
  check('reconnection writes offline change to server');
  await until(() => page.locator('.offline-queue').count().then((n) => n === 0));
  await context.setOffline(true);
  await page.locator('#tk-new').fill('Losing concurrent version'); await page.locator('#tk-new').press('Enter');
  await until(() => page.locator('.offline-queue').textContent().then((s) => s.includes('1 changes')));
  const inbox = (await api.get('inbox')).value;
  await api.put('inbox', { ...inbox, items: [...inbox.items, { id: 'remote', text: 'Newer remote version', done: false }] });
  await context.setOffline(false); await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await page.getByText('Newer remote version', { exact: true }).waitFor();
  assert.equal((await api.get('inbox')).value.items.some((x) => x.text === 'Losing concurrent version'), false);
  check('409 preserves newer server version');

  const cdp = await context.newCDPSession(page);
  let registrationId;
  cdp.on('ServiceWorker.workerRegistrationUpdated', ({ registrations }) => { registrationId = registrations.find((r) => r.scopeURL === srv.url + '/')?.registrationId || registrationId; });
  await cdp.send('ServiceWorker.enable');
  await until(() => !!registrationId);
  await cdp.send('ServiceWorker.deliverPushMessage', { origin: srv.url, registrationId, data: '{"type":"block"}' });
  await until(() => page.evaluate(async () => (await (await navigator.serviceWorker.ready).getNotifications()).some((n) => n.tag === 'block')));
  check('CDP push event displays service worker notification');
  assert.equal((await api.call('/api/push')).status, 200);
  assert.equal((await api.call('/api/push', { endpoint: 'https://127.0.0.1/push' })).status, 400);
  check('push API authenticated configuration and invalid endpoint rejection');
  console.log(`${passed} passed, 0 failed`);
} finally { await browser.close(); srv.stop(); }
