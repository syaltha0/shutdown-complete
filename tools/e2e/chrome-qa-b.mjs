import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { launch } from '../lib/browser.mjs';
import { client, startServer } from '../lib/server.mjs';
import { demoAccount } from '../lib/demo.mjs';
const srv = await startServer();
const api = await demoAccount(client(srv.url), { lang: 'tr' });
await api.put('inbox', {items: [{id:'priority', text:'QA priority', done:false, priority:1}]});
const browser = await launch();
try {
 const ctx = await browser.newContext({ reducedMotion:'reduce' });
 await ctx.addCookies([{ name:'sc_session', value:api.cookie.split('=')[1], url:srv.url }]);
 const page = await ctx.newPage();
 await page.goto(`${srv.url}/tasks`);
 await page.locator('#tk-new').waitFor();
 const colors = await page.locator('.tk-row.p1').evaluate(el => [getComputedStyle(el.querySelector('.check')).borderColor, getComputedStyle(el.querySelector('.tk-star')).color, getComputedStyle(el).getPropertyValue('--text').trim()]);
 assert.equal(colors[1], await page.locator('.tk-row.p1').evaluate(el => getComputedStyle(el).color));
 assert.equal(colors[0], await page.locator('.check').first().evaluate(el => { const copy=el.cloneNode(); const row=document.createElement('li'); row.className='tk-row'; row.append(copy); el.parentElement.parentElement.append(row); const color=getComputedStyle(copy).borderColor; row.remove(); return color; }));
 mkdirSync('reports/chrome-qa-b', {recursive:true});
 await page.screenshot({path:'reports/chrome-qa-b/priority.png'});
 console.log('PASS neutral checkbox and priority star');
 await page.locator('#tk-new').fill('QA deneme yarın 9 #İş !1');
 await page.getByText('#İş listesi yok', {exact:false}).waitFor();
 await page.locator('#tk-add-help').getByRole('button', {name:'Oluştur', exact:true}).click();
 await page.waitForFunction(() => document.querySelector('#tk-new').value === '');
 await page.waitForTimeout(900);
 const inbox = (await api.get('inbox')).value;
 const list = inbox.lists.find(l => l.name === 'İş');
 assert.ok(list);
 assert.ok(inbox.items.some(t => t.text === 'QA deneme' && t.list === list.id && t.priority === 1));
 console.log('PASS missing list preview creates list and task');
 await page.goto(`${srv.url}/metrics`);
 await page.locator('.chart svg[aria-label]').first().waitFor();
 const labels = await page.locator('.chart svg[aria-label]').evaluateAll(els => els.map(e => e.getAttribute('aria-label')));
 assert.ok(labels.some(l => l.includes('çubuk; en yüksek')));
 assert.ok(labels.every(l => !l.includes('bars from')));
 console.log('PASS Turkish chart summary');
 await page.route('**/api/account/sessions', route => route.fulfill({json:[{id:'qa',device:'Browser',current:true,created:new Date().toISOString(),lastSeen:new Date().toISOString(),ip:'127.0.0.1'}]}));
 await page.route('**/api/account/passkeys', route => route.fulfill({json:[{id:'qa',name:'Chrome on Windows',created:new Date().toISOString(),lastUsed:null}]}));
 await page.goto(`${srv.url}/settings/account`);
 await page.locator('section[aria-labelledby="a-sessions"]').getByText('Taray\u0131c\u0131', {exact:true}).waitFor();
 await page.locator('section[aria-labelledby="a-pk"]').getByText('Windows \u00fczerinde Chrome', {exact:true}).waitFor();
 // the name field suggests this browser on the machine running the test (Windows here, Linux in CI)
 assert.match(await page.locator('#a-pk-name').inputValue(), /^\S+ \u00fczerinde Chrome$/);
 console.log('PASS account has no untranslated Browser label');
} finally { await browser.close(); await srv.stop(); }
