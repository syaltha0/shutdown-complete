import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { launch } from '../lib/browser.mjs';
import { startServer, client } from '../lib/server.mjs';
import { demoAccount } from '../lib/demo.mjs';
const s = await startServer(), b = await launch();
try {
 const api = await demoAccount(client(s.url), {lang:'en'});
 const settings = (await api.get('settings')).value;
 await api.put('settings', {...settings, metrics:[...settings.metrics, {id:'qa-archived',name:'QA archived',kind:'check',unit:'',target:null,archived:true}]});
 const ctx = await b.newContext({reducedMotion:'reduce',viewport:{width:1280,height:900}});
 await ctx.addCookies([{name:'sc_session',value:api.cookie.split('=')[1],url:s.url}]);
 const p = await ctx.newPage();
 p.on('dialog', () => { throw Error('Native confirmation is forbidden'); });
 await p.goto(s.url+'/metrics'); await p.locator('.metric-seg').waitFor();
 assert.equal(await p.getByText('QA archived',{exact:true}).count(),0);
 await p.goto(s.url+'/day/2026-11-17'); await p.locator('.metrics-box').waitFor();
 assert.equal(await p.locator('.metrics-box').getByText('QA archived',{exact:true}).count(),0);
 console.log('PASS archived habit absent from metric selectors and daily metrics');
 await p.goto(s.url+'/habits'); await p.locator('.hv-name').first().click();
 const cell = p.locator('.hcell').first(); assert.match(await cell.getAttribute('aria-label'), /: (done|skipped|not yet)$/);
 assert.ok(!(await cell.getAttribute('aria-label')).includes('/'));
 await p.locator('.hv-detail button').filter({hasText:/^Archive$/}).click();
 await p.getByRole('button',{name:'Undo',exact:true}).click();
 assert.ok(await p.locator('.hv-name').count());
 await p.locator('details').last().locator('summary').click();
 await p.getByRole('button',{name:/QA archived \/ Delete for good/}).click();
 await p.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).click();
 assert.ok((await api.get('settings')).value.metrics.some(m=>m.id==='qa-archived'));
 console.log('PASS localized single habit state, archive undo and cancelled in-app deletion');
 await p.goto(s.url+'/tasks');
 const input = p.locator('.tk-add input').first(); await input.fill('QA tomorrow 9 #Missing !1');
 await p.getByText('#Missing list does not exist', {exact:false}).waitFor();
 console.log('PASS unknown list preview');
 await p.setViewportSize({width:390,height:844}); await p.goto(s.url+'/year/2026');
 await p.locator('.year-mobile-month').first().waitFor();
 assert.equal(await p.locator('.year-mobile-month').count(),12);
 assert.ok(await p.evaluate(()=>document.documentElement.scrollWidth<=390));
 assert.ok(await p.locator('.year-mobile-month').first().evaluate(e=>e.getBoundingClientRect().height>=44));
 mkdirSync('reports/shots/manual-qa-habits',{recursive:true});
 await p.screenshot({path:'reports/shots/manual-qa-habits/year-phone.png',fullPage:false});
 console.log('PASS year phone layout and accessible month targets');
 await ctx.close();
} finally { await b.close(); await s.stop(); }
